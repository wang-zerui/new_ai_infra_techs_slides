"""fig_signal.svg: put-with-signal flow control in DeepEP's hybrid dispatch (schematic timeline).
Gin ops are unordered by default, but a signal on the same context completes only after all earlier puts to that
peer are visible ([GIN] Sec. III-A, Ordering Semantics). Sender: scale-out warp; receiver: forward warp polling the
tail signal (hybrid_dispatch.cuh)."""
import os
W, H = 870, 282
ACC, ACC_F = "#1F4E79", "#DEEBF7"
CREAM_F, CREAM_S = "#FFF2CC", "#7F6000"
lanes = [("scale-out warp", 34), ("remote buffer", 98), ("tail signal", 162), ("forward warp", 226)]
LH = 36
o = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}pt" height="{H}pt" viewBox="0 0 {W} {H}" font-family="Helvetica, Arial, sans-serif">',
     '  <!-- fig_signal (generated by gen_signal.py) -->',
     '  <defs><marker id="arrA" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="8" markerHeight="8" markerUnits="userSpaceOnUse" orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 z" fill="#1F4E79"/></marker>'
     '<marker id="arrG" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="8" markerHeight="8" markerUnits="userSpaceOnUse" orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 z" fill="#7F7F7F"/></marker></defs>']
for name, y in lanes:
    o.append(f'  <text x="4" y="{y + LH / 2 + 6}" font-size="17" font-weight="bold" fill="#595959">{name}</text>')
    o.append(f'  <line x1="150" y1="{y + LH / 2}" x2="862" y2="{y + LH / 2}" stroke="#E0E0E0" stroke-width="1"/>')


def box(x0, x1, y, label, fill, stroke, tc="#222222", bold=False, dash=False):
    d = ' stroke-dasharray="4,3"' if dash else ''
    o.append(f'  <rect x="{x0}" y="{y}" width="{x1 - x0}" height="{LH}" rx="3" fill="{fill}" stroke="{stroke}" stroke-width="1.5"{d}/>')
    fw = ' font-weight="bold"' if bold else ''
    o.append(f'  <text x="{(x0 + x1) / 2}" y="{y + LH / 2 + 6}" text-anchor="middle" font-size="16"{fw} fill="{tc}">{label}</text>')


ys = dict((n, y) for n, y in lanes)
# sender: three puts then a signal, all on the same context (QP)
puts = [(160, 228, "put t1"), (234, 302, "put t2"), (308, 376, "put t3")]
for x0, x1, lab in puts:
    box(x0, x1, ys["scale-out warp"], lab, ACC_F, ACC, ACC)
box(382, 482, ys["scale-out warp"], "signal +3", ACC_F, ACC, ACC, True)
# arrivals, in any order
arr = {"t1": (300, 348), "t2": (404, 452), "t3": (352, 400)}
src = {"t1": 194, "t2": 268, "t3": 342}
for t, (x0, x1) in arr.items():
    box(x0, x1, ys["remote buffer"], t, CREAM_F, CREAM_S)
    o.append(f'  <line x1="{src[t]}" y1="{ys["scale-out warp"] + LH + 1}" x2="{(x0 + x1) / 2}" y2="{ys["remote buffer"] - 1}" stroke="#7F7F7F" stroke-width="1.5" marker-end="url(#arrG)"/>')
o.append(f'  <text x="376" y="{ys["remote buffer"] + LH + 18}" text-anchor="middle" font-size="16" font-style="italic" fill="#595959">arrive in any order</text>')
# tail signal step: 0 then 3, after all puts are visible
ylo, yhi = ys["tail signal"] + LH - 6, ys["tail signal"] + 6
o.append(f'  <path d="M152,{ylo} H556 V{yhi} H860" fill="none" stroke="{ACC}" stroke-width="2.5"/>')
o.append(f'  <text x="200" y="{ylo - 6}" font-size="16" font-weight="bold" fill="{ACC}">0</text>')
o.append(f'  <text x="600" y="{yhi + 22}" font-size="16" font-weight="bold" fill="{ACC}">3</text>')
o.append(f'  <line x1="432" y1="{ys["scale-out warp"] + LH + 1}" x2="554" y2="{yhi + 1}" stroke="{ACC}" stroke-width="2" marker-end="url(#arrA)"/>')
# receiver: polls, then consumes
for x0 in (300, 376, 452):
    box(x0, x0 + 64, ys["forward warp"], "poll", "#FFFFFF", "#7F7F7F", "#595959", dash=True)
box(566, 700, ys["forward warp"], "read t1–t3", ACC_F, ACC, ACC, True)
box(708, 860, ys["forward warp"], "TMA to peers", ACC_F, ACC, ACC)
o.append(f'  <line x1="566" y1="{yhi + 2}" x2="600" y2="{ys["forward warp"] - 1}" stroke="{ACC}" stroke-width="2" stroke-dasharray="4,3" marker-end="url(#arrA)"/>')
o.append(f'  <line x1="160" y1="272" x2="858" y2="272" stroke="#333333" stroke-width="1.5" marker-end="url(#arrG)"/>')
o.append(f'  <text x="150" y="277" text-anchor="end" font-size="16" fill="#595959">time</text>')
o.append('</svg>')
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "fig_signal.svg"), "w").write("\n".join(o) + "\n")
print("ok")
