"""fig_init.svg: host-initiated vs device-initiated EP dispatch (schematic timelines, not to scale)."""
import os
W, H = 870, 226
ACC, ACC_F = "#1F4E79", "#DEEBF7"
GRAY_F, GRAY_S = "#F2F2F2", "#595959"
RED, RED_F = "#C00000", "#FBE5E5"
lanes = {"CPU": 44, "GPU": 96, "NIC": 148}
LH = 38


def box(o, x0, x1, lane, label, fill, stroke, tc="#222222", bold=False):
    y = lanes[lane]
    o.append(f'  <rect x="{x0}" y="{y}" width="{x1 - x0}" height="{LH}" rx="3" fill="{fill}" stroke="{stroke}" stroke-width="1.5"/>')
    fw = ' font-weight="bold"' if bold else ''
    o.append(f'  <text x="{(x0 + x1) / 2}" y="{y + LH / 2 + 6}" text-anchor="middle" font-size="17"{fw} fill="{tc}">{label}</text>')


def panel(o, dx, title, kind):
    o.append(f'  <text x="{dx + 4}" y="22" font-size="18" font-weight="bold" fill="#222222">{title}</text>')
    for name, y in lanes.items():
        o.append(f'  <text x="{dx + 4}" y="{y + LH / 2 + 6}" font-size="17" font-weight="bold" fill="#595959">{name}</text>')
    X = lambda v: dx + v
    if kind == "host":
        box(o, X(56), X(116), "CPU", "launch", GRAY_F, GRAY_S)
        box(o, X(124), X(214), "CPU", "wait", RED_F, RED, RED, True)
        box(o, X(222), X(282), "CPU", "launch", GRAY_F, GRAY_S)
        box(o, X(116), X(176), "GPU", "route", GRAY_F, GRAY_S)
        o.append(f'  <rect x="{X(176)}" y="{lanes["GPU"]}" width="{X(290) - X(176)}" height="{LH}" fill="url(#hatchRed)" stroke="{RED}" stroke-width="1.5"/>')
        o.append(f'  <text x="{X(233)}" y="{lanes["GPU"] + LH / 2 + 6}" text-anchor="middle" font-size="17" font-weight="bold" fill="{RED}" paint-order="stroke" stroke="#FFFFFF" stroke-width="5">idle</text>')
        box(o, X(290), X(410), "GPU", "all-to-all", GRAY_F, GRAY_S)
        box(o, X(296), X(410), "NIC", "RDMA", GRAY_F, GRAY_S)
    else:
        box(o, X(56), X(116), "CPU", "launch", GRAY_F, GRAY_S)
        box(o, X(116), X(282), "GPU", "route + dispatch", ACC_F, ACC, ACC, True)
        box(o, X(286), X(366), "GPU", "GEMM", GRAY_F, GRAY_S)
        box(o, X(160), X(282), "NIC", "RDMA", ACC_F, ACC, ACC, True)
    o.append(f'  <line x1="{X(56)}" y1="206" x2="{X(412)}" y2="206" stroke="#333333" stroke-width="2" marker-end="url(#arrK)"/>')
    o.append(f'  <text x="{X(412)}" y="224" text-anchor="end" font-size="16" fill="#595959">time</text>')


o = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}pt" height="{H}pt" viewBox="0 0 {W} {H}" font-family="Helvetica, Arial, sans-serif">',
     '  <!-- fig_init: host-initiated vs device-initiated dispatch (generated by gen_init.py) -->',
     '  <defs><marker id="arrK" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="9" markerHeight="9" markerUnits="userSpaceOnUse" orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 z" fill="#333333"/></marker>'
     '<pattern id="hatchRed" width="6" height="6" patternUnits="userSpaceOnUse" patternTransform="rotate(45)"><rect width="6" height="6" fill="#FFFFFF"/><line x1="0" y1="0" x2="0" y2="6" stroke="#E8A0A0" stroke-width="2"/></pattern></defs>']
panel(o, 0, "(a) Host-initiated collective", "host")
o.append('  <line x1="434" y1="6" x2="434" y2="220" stroke="#BFBFBF" stroke-width="1"/>')
panel(o, 448, "(b) Device-initiated with Gin", "device")
o.append('</svg>')
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "fig_init.svg"), "w").write("\n".join(o) + "\n")
print("ok")
