"""Generate fig_hybrid_1.svg / fig_hybrid_2.svg: DeepEP v2 hybrid dispatch for one token
(artifact-centric pipeline, slide scale, 1 unit = 1pt). Step 1 = source side, step 2 adds the rail peer's
NVLink forward and the copy epilogue. Run: python3 gen_hybrid.py (writes next to this file)."""
import os

W, H = 870, 206
ACC, ACC_F = "#1F4E79", "#DEEBF7"
CREAM_F, CREAM_S = "#FFF2CC", "#7F6000"
GRAY_F, GRAY_S = "#F2F2F2", "#595959"
INK = "#222222"

CHIP_W, CHIP_H, CHIP_Y = 122, 48, 118
CHIP_X = [8 + i * 183 for i in range(5)]
GAP_C = [CHIP_X[i] + CHIP_W + 30.5 for i in range(4)]
ACT_W, ACT_H, ACT_Y = 168, 60, 12

chips = ["tokens x", "send buffer", "RDMA recv", "NVLink recv", "expert rows"]
actors = [("scale-out warp", "TMA copy + gin.put", ACC_F, ACC),
          ("NIC", "RDMA on channel QP", GRAY_F, GRAY_S),
          ("forward warp", "TMA over NVLink", ACC_F, ACC),
          ("copy epilogue", "expand per expert", ACC_F, ACC)]
ops = ["TMA", "RDMA", "NVLink", "expand"]
conts = [(2, 321, "Node A · GPU 0"), (360, 510, "Node B · GPU 0"), (549, 868, "Node B · GPU 3")]


def svg(step):
    n_chips = 3 if step == 1 else 5
    n_gaps = 2 if step == 1 else 4
    n_conts = 2 if step == 1 else 3
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}pt" height="{H}pt" viewBox="0 0 {W} {H}" '
         f'font-family="Helvetica, Arial, sans-serif">',
         f'  <!-- fig_hybrid step {step}: hybrid dispatch of one token (generated by gen_hybrid.py) -->',
         '  <defs><marker id="arrA" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="9" markerHeight="9" '
         'markerUnits="userSpaceOnUse" orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 z" fill="%s"/></marker></defs>' % ACC]
    # GPU containers
    for x0, x1, title in conts[:n_conts]:
        o.append(f'  <rect x="{x0}" y="104" width="{x1 - x0}" height="98" rx="6" fill="none" stroke="#7F7F7F" '
                 f'stroke-width="1.5" stroke-dasharray="6,4"/>')
        o.append(f'  <text x="{(x0 + x1) / 2}" y="192" text-anchor="middle" font-size="17" font-weight="bold" '
                 f'fill="#595959">{title}</text>')
    # chips (data artifacts)
    for i in range(n_chips):
        x = CHIP_X[i]
        o.append(f'  <rect x="{x}" y="{CHIP_Y}" width="{CHIP_W}" height="{CHIP_H}" rx="4" fill="{CREAM_F}" '
                 f'stroke="{CREAM_S}" stroke-width="1.5"/>')
        o.append(f'  <text x="{x + CHIP_W / 2}" y="{CHIP_Y + CHIP_H / 2 + 6.3}" text-anchor="middle" font-size="18" '
                 f'fill="{INK}">{chips[i]}</text>')
    # operation arrows + labels + actors + badges
    for i in range(n_gaps):
        x0, x1, c = CHIP_X[i] + CHIP_W + 1, CHIP_X[i + 1] - 1, GAP_C[i]
        y = CHIP_Y + CHIP_H / 2
        o.append(f'  <line x1="{x0}" y1="{y}" x2="{x1}" y2="{y}" stroke="{ACC}" stroke-width="2.5" marker-end="url(#arrA)"/>')
        name, sub, fill, stroke = actors[i]
        ax = c - ACT_W / 2
        o.append(f'  <rect x="{ax}" y="{ACT_Y}" width="{ACT_W}" height="{ACT_H}" rx="5" fill="{fill}" stroke="{stroke}" stroke-width="1.5"/>')
        tc = ACC if stroke == ACC else INK
        o.append(f'  <text x="{c}" y="{ACT_Y + 25}" text-anchor="middle" font-size="18" font-weight="bold" fill="{tc}">{name}</text>')
        o.append(f'  <text x="{c}" y="{ACT_Y + 49}" text-anchor="middle" font-size="16" fill="{INK}">{sub}</text>')
        o.append(f'  <line x1="{c}" y1="{ACT_Y + ACT_H}" x2="{c}" y2="{y - 4}" stroke="#7F7F7F" stroke-width="1.5" stroke-dasharray="3,3"/>')
        o.append(f'  <circle cx="{c}" cy="94" r="11" fill="#222222"/>')
        o.append(f'  <text x="{c}" y="99.3" text-anchor="middle" font-size="15" font-weight="bold" fill="#FFFFFF">{i + 1}</text>')
    o.append('</svg>')
    return "\n".join(o) + "\n"


here = os.path.dirname(os.path.abspath(__file__))
for s in (1, 2):
    with open(os.path.join(here, f"fig_hybrid_{s}.svg"), "w") as f:
        f.write(svg(s))
print("wrote fig_hybrid_1.svg, fig_hybrid_2.svg")
