"""fig_v1table.svg: DeepEP V1 (v1.2.1) Buffer.get_dispatch_config lookup table (subset of its 10 rows) and the
assert for any EP size outside the table. Values are config constants from deep_ep/buffer.py lines 233-242."""
import os
rows = [("8", "6 / 256", "6 / 128"), ("16", "36 / 288", "20 / 128"), ("32", "32 / 288", "32 / 128"),
        ("64", "20 / 288", "28 / 128"), ("128", "20 / 560", "32 / 128")]
W, H = 480, 304
cols = [(4, 96), (96, 286), (286, 476)]
o = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}pt" height="{H}pt" viewBox="0 0 {W} {H}" font-family="Helvetica, Arial, sans-serif">',
     '  <!-- fig_v1table: V1 per-EP-size dispatch config table (generated by gen_v1table.py) -->']
# header
o.append(f'  <rect x="4" y="4" width="472" height="52" fill="#F2F2F2" stroke="#595959" stroke-width="1.5"/>')
heads = [("EP size", None), ("NVLink chunk", "send / recv"), ("RDMA chunk", "send / recv")]
for (x0, x1), (h1, h2) in zip(cols, heads):
    cx = (x0 + x1) / 2
    if h2:
        o.append(f'  <text x="{cx}" y="26" text-anchor="middle" font-size="18" font-weight="bold" fill="#222222">{h1}</text>')
        o.append(f'  <text x="{cx}" y="47" text-anchor="middle" font-size="16" fill="#595959">{h2}</text>')
    else:
        o.append(f'  <text x="{cx}" y="36" text-anchor="middle" font-size="18" font-weight="bold" fill="#222222">{h1}</text>')
y = 56
rh = 34
for r in rows:
    o.append(f'  <rect x="4" y="{y}" width="472" height="{rh}" fill="#FFFFFF" stroke="#BFBFBF" stroke-width="1"/>')
    for (x0, x1), v in zip(cols, r):
        o.append(f'  <text x="{(x0 + x1) / 2}" y="{y + rh / 2 + 6.3}" text-anchor="middle" font-size="18" '
                 f'font-family="Menlo, \'Courier New\', monospace" fill="#222222">{v}</text>')
    y += rh
# elided rows
o.append(f'  <text x="240" y="{y + 22}" text-anchor="middle" font-size="18" fill="#595959">⋯ 10 hand-picked sizes in total ⋯</text>')
y += 34
# unsupported size
o.append(f'  <rect x="4" y="{y}" width="472" height="{rh + 4}" fill="#FBE5E5" stroke="#C00000" stroke-width="1.5"/>')
o.append(f'  <text x="50" y="{y + 25}" text-anchor="middle" font-size="18" font-family="Menlo, \'Courier New\', monospace" fill="#C00000">48</text>')
o.append(f'  <text x="286" y="{y + 25}" text-anchor="middle" font-size="18" font-weight="bold" fill="#C00000">assert: unsupported EP size</text>')
y += rh + 4
for x in (96, 286):
    o.append(f'  <line x1="{x}" y1="4" x2="{x}" y2="{56 + rh * len(rows)}" stroke="#BFBFBF" stroke-width="1"/>')
o.append('</svg>')
print(y)
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "fig_v1table.svg"), "w").write("\n".join(o) + "\n")
