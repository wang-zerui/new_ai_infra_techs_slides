"""fig_layout_1/2.svg: EPBuffer expanded receive layout on one rank with 3 local experts, expert_alignment = 4.
Toy routing (illustrative token ids): E0 <- t3 t8 t11, E1 <- t3 t5, E2 <- t1 t8 t9 t12 t14.
psum (expand mode) = aligned start + actual count = [3, 6, 13] per EPHandle docstring (deep_ep/buffers/ep.py).
Step 1: CPU sync -> exact 16 rows. Step 2: no CPU sync (decode) -> rows sized to capacity (24 here), valid range via psum."""
import os
X0, CW, CY, CH = 24, 34, 70, 46
cells = (["t3", "t8", "t11", None] + ["t3", "t5", None, None] + ["t1", "t8", "t9", "t12", "t14", None, None, None])
groups = [(0, 4, "expert 0"), (4, 8, "expert 1"), (8, 16, "expert 2")]
psum = [3, 6, 13]


def svg(step):
    n_unused = 0 if step == 1 else 8
    W, H = 870, 168
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}pt" height="{H}pt" viewBox="0 0 {W} {H}" font-family="Helvetica, Arial, sans-serif">',
         f'  <!-- fig_layout step {step} (generated by gen_layout.py) -->',
         '  <defs><pattern id="hatchGray" width="6" height="6" patternUnits="userSpaceOnUse" patternTransform="rotate(45)">'
         '<rect width="6" height="6" fill="#FFFFFF"/><line x1="0" y1="0" x2="0" y2="6" stroke="#A6A6A6" stroke-width="2"/></pattern></defs>']
    o.append(f'  <text x="{X0}" y="24" font-size="16" font-family="Menlo, \'Courier New\', monospace" fill="#1F4E79">psum_num_recv_tokens_per_expert</text>')
    for i, c in enumerate(cells):
        x = X0 + CW * i
        if c is None:
            o.append(f'  <rect x="{x}" y="{CY}" width="{CW}" height="{CH}" fill="url(#hatchGray)" stroke="#595959" stroke-width="1.2"/>')
            o.append(f'  <text x="{x + CW / 2}" y="{CY + CH / 2 + 5.5}" text-anchor="middle" font-size="15" fill="#595959" paint-order="stroke" stroke="#FFFFFF" stroke-width="4">0</text>')
        else:
            o.append(f'  <rect x="{x}" y="{CY}" width="{CW}" height="{CH}" fill="#DEEBF7" stroke="#1F4E79" stroke-width="1.2"/>')
            o.append(f'  <text x="{x + CW / 2}" y="{CY + CH / 2 + 5.5}" text-anchor="middle" font-size="15" fill="#222222">{c}</text>')
    for j in range(n_unused):
        x = X0 + CW * (len(cells) + j)
        o.append(f'  <rect x="{x}" y="{CY}" width="{CW}" height="{CH}" fill="#FFFFFF" stroke="#A6A6A6" stroke-width="1.2" stroke-dasharray="4,3"/>')
    # brackets
    spans = list(groups) + ([(16, 24, "unused capacity")] if n_unused else [])
    for a, b, lab in spans:
        xa, xb = X0 + CW * a + 3, X0 + CW * b - 3
        col = "#1F4E79" if not lab.startswith("unused") else "#7F7F7F"
        o.append(f'  <path d="M{xa},{CY + CH + 8} V{CY + CH + 16} H{xb} V{CY + CH + 8}" fill="none" stroke="{col}" stroke-width="2"/>')
        o.append(f'  <text x="{(xa + xb) / 2}" y="{CY + CH + 40}" text-anchor="middle" font-size="18" font-weight="bold" fill="{col}">{lab}</text>')
    # psum markers
    for p in psum:
        x = X0 + CW * p
        o.append(f'  <line x1="{x}" y1="{CY - 14}" x2="{x}" y2="{CY - 1}" stroke="#1F4E79" stroke-width="2.5"/>')
        o.append(f'  <text x="{x}" y="{CY - 20}" text-anchor="middle" font-size="18" font-weight="bold" fill="#1F4E79">{p}</text>')
    o.append('</svg>')
    return "\n".join(o) + "\n"


here = os.path.dirname(os.path.abspath(__file__))
for s in (1, 2):
    open(os.path.join(here, f"fig_layout_{s}.svg"), "w").write(svg(s))
print("ok")
