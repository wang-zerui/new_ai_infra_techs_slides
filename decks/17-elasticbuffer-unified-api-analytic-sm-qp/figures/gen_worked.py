"""fig_worked_1/2/3.svg: worked example of DeepEP's analytic SM count for hybrid EP 8x4, DeepSeek-V3 routing
(256 experts, top-8), V2.0 constants (per-SM write 50 GB/s, x1.25, round to even). All numbers derived in
notes/sources.md (slide 9 rows)."""
import os
W, H = 870, 238
PW, GAP = 280, 15
panels = [
    ("1", "Routing statistics", ["top-8 of 256 experts"], "7.27 GPUs", ["on 3.61 nodes", "per token"]),
    ("2", "Bottleneck link", ["RDMA 0.37 B ÷ 50 GB/s", "NVLink 0.875 B ÷ 160 GB/s"], "134 GB/s", ["delivered · RDMA-bound"]),
    ("3", "SM count", ["1.26 B SM writes per byte", "169 GB/s ÷ 50 GB/s = 3.4"], "6 SMs", ["after +25% and rounding"]),
]


def svg(step):
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}pt" height="{H}pt" viewBox="0 0 {W} {H}" font-family="Helvetica, Arial, sans-serif">',
         f'  <!-- fig_worked step {step} (generated by gen_worked.py) -->']
    for i, (num, title, pre, big, post) in enumerate(panels[:step]):
        x = i * (PW + GAP)
        cx = x + PW / 2
        o.append(f'  <rect x="{x + 1}" y="2" width="{PW - 2}" height="{H - 4}" rx="6" fill="#FFFFFF" stroke="#1F4E79" stroke-width="1.5"/>')
        o.append(f'  <rect x="{x + 1}" y="2" width="{PW - 2}" height="44" rx="6" fill="#DEEBF7" stroke="#1F4E79" stroke-width="1.5"/>')
        o.append(f'  <circle cx="{x + 26}" cy="24" r="12" fill="#222222"/>')
        o.append(f'  <text x="{x + 26}" y="29.5" text-anchor="middle" font-size="15" font-weight="bold" fill="#FFFFFF">{num}</text>')
        o.append(f'  <text x="{cx + 12}" y="30.5" text-anchor="middle" font-size="19" font-weight="bold" fill="#1F4E79">{title}</text>')
        y = 80
        for line in pre:
            o.append(f'  <text x="{cx}" y="{y}" text-anchor="middle" font-size="17" fill="#222222">{line}</text>')
            y += 26
        y = max(y, 132) + 26
        o.append(f'  <text x="{cx}" y="{y}" text-anchor="middle" font-size="34" font-weight="bold" fill="#1F4E79">{big}</text>')
        y += 34
        for line in post:
            o.append(f'  <text x="{cx}" y="{y}" text-anchor="middle" font-size="17" fill="#595959">{line}</text>')
            y += 24
    o.append('</svg>')
    return "\n".join(o) + "\n"


here = os.path.dirname(os.path.abspath(__file__))
for s in (1, 2, 3):
    open(os.path.join(here, f"fig_worked_{s}.svg"), "w").write(svg(s))
print("ok")
